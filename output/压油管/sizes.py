# 按实价最小二乘拟合（自变量=内径mm）：
#   1层 = 1.634 + 0.5798×ID   （4 个实价点，最大偏差 4.4%）
#   4层 = -1.068 + 1.3281×ID  （3 个实价点，最大偏差 5.4%）
# 2层在数据区间内恰好比 1层贵 1.0 元/米；外推到大口径时按口径放大，
# 因为第二层钢丝在粗管上用料更多，不可能还是固定 1 元。
# 3层没有实价，取 2层 与 4层 的中值。


def _round_est(v):
    return round(v * 2) / 2          # 推算值取整到 0.5，提示这是估价不是实价


def price_of(bcode, lcode):
    """返回 (价格, 来源)。来源为 '实价' 或 '推算'。查不到返回 (None, '')。"""
    key = bcode + lcode
    if key in PRICE_KNOWN:
        return PRICE_KNOWN[key], "实价"
    idmm = BY_CODE[bcode][3]
    p1 = 1.634 + 0.5798 * idmm
    gap = max(1.0, (idmm / 12.7) ** 0.8)
    p2 = p1 + gap
    # 4层拟合区间是 19~32；往小口径外推会偏低（实测 4层/2层 约 1.7~1.9 倍），取两者较大值
    p4 = max(-1.068 + 1.3281 * idmm, 1.7 * p2)
    if lcode in ("03", "04") and bcode in ("06", "08"):
        return None, ""              # 一般不做这么小的缠绕管
    est = {"01": p1, "02": p2, "03": (p2 + p4) / 2, "04": p4}.get(lcode)
    return (_round_est(est), "推算") if est else (None, "")
