def field_name(thread_disp, seat, bend, gender):
    """还原成现场标签的写法：22×1.5 A型弯芯 / 3分英制A型面"""
    sep = " " if "分" not in thread_disp and "寸" not in thread_disp else ""
    return f"{thread_disp}{sep}{seat}型{bend}{gender}"


def sku_of(tcode, seat, bend, gender):
    """M22x1.5-A-芯 / M22x1.5-A-弯-芯 / G3/8-C-面"""
    parts = [tcode, seat]
    if bend:
        parts.append(bend)
    parts.append(gender)
    return "-".join(parts)


